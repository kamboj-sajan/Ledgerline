// Command fraudeval replays two public datasets through Ledgerline's fraud
// rules, tunes each threshold on the earlier part of the data, reports
// precision, recall and F1 on the later part, and writes docs/fraud-eval.md.
//
//	scripts/download-datasets.sh
//	go run ./cmd/fraudeval
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"runtime"
	"strings"
	"time"

	"github.com/kamboj-sajan/ledgerline/internal/fraud"
	"github.com/kamboj-sajan/ledgerline/internal/fraud/eval"
)

var quantiles = []float64{0.5, 0.6, 0.7, 0.8, 0.85, 0.9, 0.93, 0.95, 0.97, 0.98, 0.99, 0.995, 0.998, 0.999}

func main() {
	ulbPath := flag.String("ulb", "data/ulb/creditcard.csv", "ULB creditcard.csv")
	trainPath := flag.String("sparkov-train", "data/sparkov/fraudTrain.csv", "Sparkov fraudTrain.csv")
	testPath := flag.String("sparkov-test", "data/sparkov/fraudTest.csv", "Sparkov fraudTest.csv")
	out := flag.String("out", "docs/fraud-eval.md", "report to write")
	configOut := flag.String("config-out", "", "also write the tuned Sparkov thresholds as a fraud config JSON")
	flag.Parse()

	start := time.Now()
	var b strings.Builder
	header(&b)
	ulb(&b, *ulbPath)
	tuned := sparkov(&b, *trainPath, *testPath)
	fmt.Fprintf(&b, "\n---\n\nGenerated by `go run ./cmd/fraudeval` in %s (Go %s, %s/%s, %d CPUs) on %s.\n",
		time.Since(start).Round(time.Second), runtime.Version(), runtime.GOOS, runtime.GOARCH, runtime.NumCPU(), time.Now().UTC().Format("2006-01-02"))

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil { //nolint:gosec // a report meant to be readable
		fail(err)
	}
	fmt.Println("wrote", *out)
	if *configOut != "" {
		j, _ := json.MarshalIndent(tuned, "", "  ")
		if err := os.WriteFile(*configOut, append(j, '\n'), 0o644); err != nil { //nolint:gosec // config meant to be readable
			fail(err)
		}
		fmt.Println("wrote", *configOut)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "fraudeval:", err)
	os.Exit(1)
}

func header(b *strings.Builder) {
	b.WriteString(`# Fraud rules evaluation

This report is **generated** by ` + "`cmd/fraudeval`" + ` from the datasets downloaded with
` + "`scripts/download-datasets.sh`" + `. Every number below comes from that run; rerun it to
reproduce them. The harness calls the same ` + "`fraud.Config.Signals`" + ` and
` + "`fraud.Config.Fires`/`Decide`" + ` functions the API runs at authorization.

**Method.** Each dataset is replayed in time order. For each rule, every candidate threshold is
scored on the *tuning* split (the earlier data), and the one with the best F1 there is chosen.
Results are then reported on the *held-out* split (the later data), which plays no part in the
choice. "Flagged" means the rule fired (review or block). Both datasets are heavily imbalanced
(well under 1% fraud), so **accuracy is not reported**: flagging nothing would score above 99%.
Precision, recall and F1 are reported instead.

`)
}

func row(b *strings.Builder, name, threshold string, p eval.Point) {
	t := p.Test
	fmt.Fprintf(b, "| %s | %s | %.3f | %d | %d | %d | %d | %.3f | %.3f | %.3f | %.2f%% |\n",
		name, threshold, p.Tune.F1(), t.TP, t.FP, t.FN, t.TN, t.Precision(), t.Recall(), t.F1(), 100*t.FlagRate())
}

const resultHeader = "| Rule | Chosen threshold | Tune F1 | Test TP | Test FP | Test FN | Test TN | Test precision | Test recall | Test F1 | Test flag rate |\n|---|---|---|---|---|---|---|---|---|---|---|\n"

func sweepTable(b *strings.Builder, title string, points []eval.Point, best int, format func(float64) string) {
	fmt.Fprintf(b, "\n<details><summary>Sweep: %s</summary>\n\n| Threshold | Tune P | Tune R | Tune F1 | Test P | Test R | Test F1 |\n|---|---|---|---|---|---|---|\n", title)
	for i, p := range points {
		mark := ""
		if i == best {
			mark = " **(chosen)**"
		}
		fmt.Fprintf(b, "| %s%s | %.3f | %.3f | %.3f | %.3f | %.3f | %.3f |\n", format(p.Threshold), mark,
			p.Tune.Precision(), p.Tune.Recall(), p.Tune.F1(), p.Test.Precision(), p.Test.Recall(), p.Test.F1())
	}
	b.WriteString("\n</details>\n")
}

func baseRates(b *strings.Builder, name string, xs []eval.Example) {
	fraudN := 0
	for _, e := range xs {
		if e.Fraud {
			fraudN++
		}
	}
	fmt.Fprintf(b, "| %s | %d | %d | %.3f%% |\n", name, len(xs), fraudN, 100*float64(fraudN)/float64(max(1, len(xs))))
}

func cents(v float64) string { return fmt.Sprintf("%.2f", v/100) }

func ulb(b *strings.Builder, path string) {
	all, err := eval.LoadULB(path)
	if err != nil {
		fail(err)
	}
	cut := len(all) * 7 / 10
	tune, test := all[:cut], all[cut:]

	b.WriteString(`## ULB credit-card fraud (Kaggle mlg-ulb/creditcardfraud)

European cardholders over two days in September 2013 (per the dataset's description). Only ` + "`Time`" + ` and ` + "`Amount`" + ` are raw
fields. ` + "`V1`–`V28`" + ` are anonymised PCA components, and **there is no card identifier and no
location**. So velocity, relative-amount and geography rules cannot be computed, and **this
dataset can only test the absolute amount rule.** Split by time: the first 70% of
transactions for tuning, the last 30% held out.

| Split | Transactions | Fraud | Base rate |
|---|---|---|---|
`)
	baseRates(b, "tune (first 70%)", tune)
	baseRates(b, "test (last 30%)", test)
	b.WriteString("\n")

	var amounts []float64
	for _, e := range tune {
		amounts = append(amounts, float64(e.Tx.Amount))
	}
	fires := func(th float64, e eval.Example) bool {
		var c fraud.Config
		c.AmountAbsolute.Max = map[string]int64{"EUR": int64(th)}
		ok, _ := c.Fires(fraud.RuleAmountAbsolute, e.Tx, fraud.Signals{})
		return ok
	}
	points, best := eval.Sweep(tune, test, eval.Quantiles(amounts, quantiles), fires)
	b.WriteString(resultHeader)
	row(b, "amount_absolute (amount > threshold, EUR)", "€"+cents(points[best].Threshold), points[best])
	sweepTable(b, "amount_absolute on ULB (threshold in EUR)", points, best, func(v float64) string { return "€" + cents(v) })
	b.WriteString(`
Fraud in this dataset is not concentrated among large amounts, so a "large amount" rule is a
weak detector here, and the table above shows how weak. The PCA features carry most of the
signal, and a rules engine over raw fields cannot use them.

`)
}

// sparkov tunes every rule on the train file, reports on the test file, and
// returns the tuned config.
func sparkov(b *strings.Builder, trainPath, testPath string) fraud.Config {
	windows := []time.Duration{time.Hour, 24 * time.Hour}
	var base fraud.Config
	base.HistoryWindow = fraud.Duration{Duration: 30 * 24 * time.Hour}
	base.AmountRelative.MinHistory = 5
	train, test, err := eval.LoadSparkov(trainPath, testPath, base, windows)
	if err != nil {
		fail(err)
	}

	cards := map[string]bool{}
	for _, e := range append(train[:len(train):len(train)], test...) {
		cards[e.Tx.CardFingerprint] = true
	}
	fmt.Fprintf(b, "## Sparkov simulated transactions (Kaggle kartik2112/fraud-detection)\n\nSimulated with the Sparkov generator: %d distinct US cards (counted in this run), with card\nnumber, Unix time, amount, and cardholder and merchant latitude/longitude. ", len(cards))
	b.WriteString(`Tuned on
` + "`fraudTrain.csv`" + ` (earlier dates), reported on ` + "`fraudTest.csv`" + ` (later dates). Both files are
replayed as one time-ordered stream, so a test transaction sees the card's earlier train
transactions as history, as production would. Labels are never used to compute signals.
History window: 30 days. ` + "`amount_relative`" + ` needs at least 5 earlier transactions.
**Geography:** the data is US-only, so there is no country mismatch to test. Geo is measured as
the cardholder-to-merchant distance (` + "`geo_distance`" + `).

| Split | Transactions | Fraud | Base rate |
|---|---|---|---|
`)
	baseRates(b, "tune (fraudTrain.csv)", train)
	baseRates(b, "test (fraudTest.csv)", test)
	b.WriteString("\n")

	type ruleSweep struct {
		name       string
		window     int // index into windows; -1 when the window does not matter
		candidates []float64
		fires      func(th float64, e eval.Example) bool
		format     func(float64) string
		points     []eval.Point
		best       int
	}
	collect := func(f func(e eval.Example) float64) []float64 {
		var out []float64
		for _, e := range train {
			out = append(out, f(e))
		}
		return out
	}
	usd := func(v float64) string { return "$" + cents(v) }
	plain := func(v float64) string { return fmt.Sprintf("%g", v) }
	km := func(v float64) string { return fmt.Sprintf("%g km", v) }

	sweeps := []*ruleSweep{{
		name: "amount_absolute", window: -1, format: usd,
		candidates: eval.Quantiles(collect(func(e eval.Example) float64 { return float64(e.Tx.Amount) }), quantiles),
		fires: func(th float64, e eval.Example) bool {
			c := base
			c.AmountAbsolute.Max = map[string]int64{"USD": int64(th)}
			ok, _ := c.Fires(fraud.RuleAmountAbsolute, e.Tx, e.Sigs[0])
			return ok
		},
	}, {
		name: "amount_relative", window: -1, format: func(v float64) string { return fmt.Sprintf("%g× median", v) },
		candidates: []float64{1.5, 2, 3, 4, 5, 6, 8, 10, 15, 20},
		fires: func(th float64, e eval.Example) bool {
			c := base
			c.AmountRelative.MaxMultiple = th
			ok, _ := c.Fires(fraud.RuleAmountRelative, e.Tx, e.Sigs[0])
			return ok
		},
	}, {
		name: "geo_distance", window: -1, format: km,
		candidates: []float64{25, 50, 75, 100, 110, 120, 130, 140, 150},
		fires: func(th float64, e eval.Example) bool {
			c := base
			c.Distance.MaxKm = th
			ok, _ := c.Fires(fraud.RuleDistance, e.Tx, e.Sigs[0])
			return ok
		},
	}}
	for wi, w := range windows {
		sweeps = append(sweeps, &ruleSweep{
			name: "velocity_count (" + w.String() + ")", window: wi, format: plain,
			candidates: []float64{1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20, 25, 30},
			fires: func(th float64, e eval.Example) bool {
				c := base
				c.Velocity.MaxCount = int(th)
				ok, _ := c.Fires(fraud.RuleVelocityCount, e.Tx, e.Sigs[wi])
				return ok
			},
		}, &ruleSweep{
			name: "velocity_amount (" + w.String() + ")", window: wi, format: usd,
			candidates: eval.Quantiles(collect(func(e eval.Example) float64 { return float64(e.Sigs[wi].VelocityAmount) }), quantiles),
			fires: func(th float64, e eval.Example) bool {
				c := base
				c.Velocity.MaxAmount = map[string]int64{"USD": int64(th)}
				ok, _ := c.Fires(fraud.RuleVelocityAmount, e.Tx, e.Sigs[wi])
				return ok
			},
		})
	}
	for _, s := range sweeps {
		s.points, s.best = eval.Sweep(train, test, s.candidates, s.fires)
	}

	b.WriteString("### Per rule\n\n" + resultHeader)
	for _, s := range sweeps {
		row(b, s.name, s.format(s.points[s.best].Threshold), s.points[s.best])
	}

	// The engine has one velocity window: use the one whose better velocity
	// rule scores higher on the tuning split.
	bestWindow, bestF1 := 0, -1.0
	for _, s := range sweeps {
		if s.window >= 0 && s.points[s.best].Tune.F1() > bestF1 {
			bestWindow, bestF1 = s.window, s.points[s.best].Tune.F1()
		}
	}

	// Combine rules by greedy forward selection on the tuning split only:
	// start with no rules, and in each round enable the rule (at its tuned
	// threshold) that most improves the combined F1 of fraud.Config.Decide.
	// Stop when no rule improves it. A rule whose best threshold is still
	// noise (it would only add false positives) stays disabled.
	enable := func(c *fraud.Config, s *ruleSweep) {
		th := s.points[s.best].Threshold
		switch {
		case s.name == "amount_absolute":
			c.AmountAbsolute.Max = map[string]int64{"USD": int64(th)}
		case s.name == "amount_relative":
			c.AmountRelative.MaxMultiple = th
		case s.name == "geo_distance":
			c.Distance.MaxKm = th
		case strings.HasPrefix(s.name, "velocity_count"):
			c.Velocity.MaxCount = int(th)
		case strings.HasPrefix(s.name, "velocity_amount"):
			c.Velocity.MaxAmount = map[string]int64{"USD": int64(th)}
		}
	}
	score := func(c fraud.Config, xs []eval.Example) eval.Confusion {
		return eval.Score(xs, func(e eval.Example) bool { return c.Decide(e.Tx, e.Sigs[bestWindow]).Decision != fraud.Allow })
	}
	var pool []*ruleSweep
	for _, s := range sweeps {
		if s.window < 0 || s.window == bestWindow {
			pool = append(pool, s)
		}
	}
	tuned := base
	tuned.Velocity.Window = fraud.Duration{Duration: windows[bestWindow]}
	type step struct {
		rule string
		pt   eval.Point
	}
	var steps []step
	current := 0.0
	for len(pool) > 0 {
		bestI, bestCfg, bestPt := -1, tuned, eval.Point{}
		for i, s := range pool {
			c := tuned
			enable(&c, s)
			if tune := score(c, train); tune.F1() > current && (bestI < 0 || tune.F1() > bestPt.Tune.F1()) {
				bestI, bestCfg, bestPt = i, c, eval.Point{Tune: tune}
			}
		}
		if bestI < 0 {
			break
		}
		bestPt.Test = score(bestCfg, test)
		steps = append(steps, step{rule: pool[bestI].name + " > " + pool[bestI].format(pool[bestI].points[pool[bestI].best].Threshold), pt: bestPt})
		tuned, current = bestCfg, bestPt.Tune.F1()
		pool = append(pool[:bestI], pool[bestI+1:]...)
	}
	var left []string
	for _, s := range pool {
		left = append(left, "`"+s.name+"`")
	}

	fmt.Fprintf(b, "\n### Combined\n\nRules are combined by **greedy forward selection on the tuning split**. Start with no rules; in\neach round, enable the rule (at its tuned threshold) that most improves the combined tuning F1,\nas computed by `fraud.Config.Decide` with a %s velocity window (the window whose velocity\nrules scored best on tuning). Stop when nothing improves it. The test split is only read to\nreport each step.\n\n| Step | Rule enabled | Tune F1 | Test TP | Test FP | Test FN | Test TN | Test precision | Test recall | Test F1 | Test flag rate |\n|---|---|---|---|---|---|---|---|---|---|---|\n", windows[bestWindow])
	for i, st := range steps {
		row(b, fmt.Sprint(i+1), st.rule, st.pt)
	}
	if len(left) > 0 {
		fmt.Fprintf(b, "\nLeft disabled (adding any of them lowered the tuning F1): %s.\n", strings.Join(left, ", "))
	}
	if len(steps) > 0 {
		final := steps[len(steps)-1].pt.Test
		fmt.Fprintf(b, "\n**Final combined detector on the held-out test split: precision %.3f, recall %.3f, F1 %.3f, flagging %.2f%% of transactions.**\n",
			final.Precision(), final.Recall(), final.F1(), 100*final.FlagRate())
	}

	b.WriteString("\n### Threshold sweeps\n\nThe chosen row is the best F1 on the tuning split. The test columns show how each choice\ngeneralises.\n")
	for _, s := range sweeps {
		sweepTable(b, s.name, s.points, s.best, s.format)
	}
	return tuned
}
